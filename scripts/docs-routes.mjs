import assert from 'node:assert/strict';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createMarkdownRenderer } from 'vitepress';
import { canonicalDocumentationLink } from '../.vitepress/data/redirects.ts';

const root = fileURLToPath(new URL('../', import.meta.url));
const manifestPath = resolve(root, '.vitepress/data/site.json');
const site = JSON.parse(readFileSync(manifestPath, 'utf8'));
const fileFor = (route) => resolve(root, `${route.replace(/^\//, '')}${route.endsWith('/') ? 'index' : ''}.md`);
const mode = process.argv[2] ?? '--check';
assert.ok(['--capture', '--write', '--check', '--link-patch'].includes(mode), `Unknown docs route mode: ${mode}`);

const idsFrom = (markdown, source) => [...new Set([...markdown.render(source).matchAll(/\bid="([^"]+)"/g)].map((match) => match[1]))];

if (mode === '--capture') {
    const markdown = await createMarkdownRenderer(root);
    for (const entry of site.redirects) {
        const source = readFileSync(fileFor(entry.from), 'utf8');
        const ids = source.includes('<CompatibilityRedirect') ? Object.keys(entry.fragments ?? {}) : idsFrom(markdown, source);
        assert.ok(ids.length, `No captured fragment IDs for ${entry.from}`);
        const targetPath = fileFor(entry.to.split('#')[0]);
        const targetIds = existsSync(targetPath) ? idsFrom(markdown, readFileSync(targetPath, 'utf8')) : [];
        entry.fragments = Object.fromEntries(
            ids.map((id) => {
                const prior = entry.fragments?.[id] ?? entry.to;
                return [id, prior === entry.to && !entry.to.includes('#') && targetIds.includes(id) ? `${entry.to}#${id}` : prior];
            }),
        );
    }
    writeFileSync(manifestPath, `${JSON.stringify(site, null, 4)}\n`);
} else if (mode === '--link-patch') {
    function files(directory) {
        return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
            const path = resolve(directory, entry.name);
            if (entry.isDirectory()) return ['api', 'packages', 'reference'].includes(entry.name) ? [] : files(path);
            return path.endsWith('.md') ? [path] : [];
        });
    }
    const sections = [];
    for (const file of files(resolve(root, 'en'))) {
        const changes = readFileSync(file, 'utf8')
            .split('\n')
            .flatMap((line) => {
                const after = line.replace(/(?<=\]\(|href=["'])\/en\/(?:packages|reference)\/[^\s)"']*/g, canonicalDocumentationLink);
                return after === line ? [] : [`@@\n-${line}\n+${after}`];
            });
        if (changes.length) sections.push(`*** Update File: ${relative(root, file)}\n${changes.join('\n')}`);
    }
    console.log(`*** Begin Patch\n${sections.join('\n')}\n*** End Patch`);
} else {
    for (const entry of site.redirects) {
        const source = `---\ntitle: Moved documentation\ndocType: compatibility\nlayout: page\nsearch: false\n---\n\n<!-- Generated by scripts/docs-routes.mjs from the canonical route map. -->\n<CompatibilityRedirect from="${entry.from}" />\n`;
        if (mode === '--write') writeFileSync(fileFor(entry.from), source);
        else assert.equal(readFileSync(fileFor(entry.from), 'utf8'), source, `Run pnpm docs:routes to synchronize ${entry.from}`);
    }
}
if (mode !== '--link-patch') console.log(`Documentation routes ${mode}: ${site.redirects.length} compatibility entries.`);
